import { Database } from "bun:sqlite";
import { copyFileSync, rmSync } from "node:fs";
rmSync(".m4q3b.db", { force: true });
copyFileSync("db/custom.db", ".m4q3b.db");
const db = new Database(".m4q3b.db", { readonly: true });
const q = (l: string, s: string) => { try { console.log(l + ":", JSON.stringify(db.query(s).all())); } catch (e) { console.log(l + " ERR:", e instanceof Error ? e.message : String(e)); } };
q("products_schema", `SELECT sql FROM sqlite_master WHERE name='products'`);
q("order_items_schema", `SELECT sql FROM sqlite_master WHERE name='order_items'`);
q("cat_avg", `SELECT category, ROUND(AVG(price),2) AS ap, COUNT(*) AS n FROM products GROUP BY category`);
q("prod_above_cat_avg", `SELECT COUNT(*) AS n FROM products p WHERE p.price > (SELECT AVG(p2.price) FROM products p2 WHERE p2.category = p.category)`);
q("prod_below_cat_avg", `SELECT COUNT(*) AS n FROM products p WHERE p.price < (SELECT AVG(p2.price) FROM products p2 WHERE p2.category = p.category)`);
q("cat_counts", `SELECT category, COUNT(*) AS n FROM products GROUP BY category`);
q("max_price_per_cat", `SELECT category, MAX(price) AS mx FROM products GROUP BY category`);
q("supp_prod_count_corr", `SELECT s.name, (SELECT COUNT(*) FROM products p WHERE p.supplier_id = s.id) AS n FROM suppliers s ORDER BY n DESC`);
q("oi_qty_above_order_avg", `SELECT COUNT(*) AS n FROM order_items oi WHERE oi.quantity > (SELECT AVG(o2.quantity) FROM order_items o2 WHERE o2.order_id = oi.order_id)`);
q("suppliers_schema", `SELECT sql FROM sqlite_master WHERE name='suppliers'`);
q("cust_above_own_spend", `SELECT COUNT(*) AS n FROM orders o WHERE o.total > (SELECT SUM(o2.total) FROM orders o2 WHERE o2.customer_id = o.customer_id)`);
q("pending_holders", `SELECT COUNT(DISTINCT customer_id) AS n FROM orders WHERE status = 'pending'`);
q("shipped_holders", `SELECT COUNT(DISTINCT customer_id) AS n FROM orders WHERE status = 'shipped'`);
db.close(); rmSync(".m4q3b.db", { force: true });
