// L58 case-study batch — splices the 5 new EXPECTED entries (l58-p1..p5)
// into src/lib/curriculum/expected.ts, preserving every existing entry and
// replicating gen-expected.ts formatting exactly (same normalizeCell rounding,
// same JSON.stringify(…, null, 2)). READ-ONLY against the DB: runs each new
// solution, never writes, never resets rows that persist (reset is the seed).
import { writeFileSync } from "node:fs";
import { PrismaClient } from "@prisma/client";
import { resetDatabase } from "../src/lib/sample-db";
import { EXPECTED } from "../src/lib/curriculum/expected";

const FILE = "src/lib/curriculum/expected.ts";
const BANNER =
  "// AUTO-GENERATED by scripts/gen-expected.ts — do not edit by hand.\n// Grading targets: each problem's solution executed on the seed database.\n// Write/DDL problems were executed sandboxed (transaction + rollback).\n\nexport const EXPECTED: Record<string, { columns: string[]; rows: Array<Array<string | number | null>>; changes?: number }> = ";

function normCell(v: unknown): string | number | null {
  if (v === null || v === undefined) return null;
  if (typeof v === "bigint") return Number(v);
  if (typeof v === "number") return Math.round(v * 100) / 100;
  return String(v);
}

const SOL: Record<string, string> = {
  "l58-p1": `SELECT mon,
  ROUND(collected / 100.0, 2) AS collected,
  ROUND(100.0 * (collected - prev) / prev, 1) AS pct
FROM (
  SELECT strftime('%Y-%m', paid_on) AS mon,
    SUM(amount_cents) AS collected,
    LAG(SUM(amount_cents)) OVER (
      ORDER BY strftime('%Y-%m', paid_on)
    ) AS prev
  FROM payments
  GROUP BY mon
)
ORDER BY mon;`,
  "l58-p2": `SELECT name,
  billed,
  collected,
  ROUND(billed - collected, 2) AS net_owed
FROM (
  SELECT c.name AS name,
    (SELECT COALESCE(SUM(i.amount_cents), 0)
       FROM invoices i
       WHERE i.customer_id = c.id AND i.status != 'void') / 100.0 AS billed,
    COALESCE((SELECT SUM(p.amount_cents)
       FROM payments p
       JOIN invoices i ON i.id = p.invoice_id
       WHERE i.customer_id = c.id AND i.status != 'void'), 0) / 100.0 AS collected
  FROM customers c
  WHERE EXISTS (SELECT 1 FROM invoices i
    WHERE i.customer_id = c.id AND i.status != 'void')
)
ORDER BY net_owed DESC, name;`,
  "l58-p3": `SELECT SUBSTR(due_on, 1, 7) AS due_mon,
  COUNT(*) AS n,
  ROUND(SUM(amount_cents - COALESCE(
    (SELECT SUM(p.amount_cents) FROM payments p
     WHERE p.invoice_id = invoices.id), 0)) / 100.0, 2) AS due_dollars
FROM invoices
WHERE status = 'open'
GROUP BY due_mon
ORDER BY due_mon;`,
  "l58-p4": `SELECT
  ROUND((SELECT SUM(i.amount_cents - COALESCE(
    (SELECT SUM(p.amount_cents) FROM payments p
     WHERE p.invoice_id = i.id), 0))
    FROM invoices i
    WHERE i.status != 'void') / 100.0, 2) AS subledger,
  ROUND((SELECT SUM(debit_cents) - SUM(credit_cents)
    FROM ledger_entries
    WHERE account = 'accounts_receivable') / 100.0, 2) AS ledger_ar,
  ROUND(((SELECT SUM(i.amount_cents - COALESCE(
    (SELECT SUM(p.amount_cents) FROM payments p
     WHERE p.invoice_id = i.id), 0))
    FROM invoices i
    WHERE i.status != 'void')
  - (SELECT SUM(debit_cents) - SUM(credit_cents)
    FROM ledger_entries
    WHERE account = 'accounts_receivable')) / 100.0, 2) AS gap;`,
  "l58-p5": `SELECT name,
  ROUND(net / 100.0, 2) AS net_owed,
  ROUND(CUME_DIST() OVER (ORDER BY net), 3) AS cd
FROM (
  SELECT c.name AS name,
    (SELECT SUM(i.amount_cents) FROM invoices i
      WHERE i.customer_id = c.id AND i.status != 'void')
    - COALESCE((SELECT SUM(p.amount_cents)
      FROM payments p
      JOIN invoices i ON i.id = p.invoice_id
      WHERE i.customer_id = c.id AND i.status != 'void'), 0) AS net
  FROM customers c
  WHERE EXISTS (SELECT 1 FROM invoices i
    WHERE i.customer_id = c.id AND i.status != 'void')
)
ORDER BY net_owed DESC, name;`,
};

const db = new PrismaClient({ log: [] });

async function main() {
  await resetDatabase();

  const fresh: Record<string, { columns: string[]; rows: unknown[][] }> = {};
  let failures = 0;
  for (const [id, sql] of Object.entries(SOL)) {
    try {
      const raw = (await db.$queryRawUnsafe(sql)) as Array<Record<string, unknown>>;
      const columns = raw.length ? Object.keys(raw[0]) : [];
      const rows = raw.map((r) => columns.map((c) => normCell(r[c])));
      fresh[id] = { columns, rows };
      console.log(`OK   ${id}  ${rows.length} rows  first=${JSON.stringify(rows[0])}  last=${JSON.stringify(rows[rows.length - 1])}`);
    } catch (err) {
      failures++;
      console.error(`FAIL ${id}: ${err instanceof Error ? err.message : err}`);
    }
  }
  await db.$disconnect();
  if (failures > 0) process.exit(1);

  const merged = { ...EXPECTED, ...fresh };
  writeFileSync(FILE, BANNER + JSON.stringify(merged, null, 2) + ";\n");
  console.log(`wrote ${FILE}: ${Object.keys(merged).length} entries (+${Object.keys(fresh).length})`);
}

main();
