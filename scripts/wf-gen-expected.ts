// Generates src/lib/curriculum/windows/expected-wf.ts — grading targets for
// every window-functions problem — by running each solution against the
// freshly seeded database. Also validates bank hygiene:
//   * duplicate ids / duplicate normalized solutions
//   * identical result sets between two problems (repetition check)
//   * empty results (warn — a 0-row grading target is a bad problem)
//   * windows missing from the solution text (sanity)
//
// Run: npx tsx scripts/wf-gen-expected.ts

import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { db } from "../src/lib/db";
import { resetDatabase } from "../src/lib/sample-db";
import type { Problem } from "../src/lib/curriculum/types";

function normalizeCell(v: unknown): string | number | null {
  if (v === null || v === undefined) return null;
  if (typeof v === "bigint") return Number(v);
  if (typeof v === "number") return Math.round(v * 100) / 100;
  return String(v);
}

function normSql(sql: string): string {
  return sql.replace(/\s+/g, " ").trim().toLowerCase().replace(/;$/, "");
}

function resultHash(columns: string[], rows: unknown[][]): string {
  return JSON.stringify([columns.map((c) => c.toLowerCase()), rows]);
}

async function load(): Promise<Problem[]> {
  const files = [
    "../src/lib/curriculum/windows/problems-a",
    "../src/lib/curriculum/windows/problems-b",
    "../src/lib/curriculum/windows/problems-c",
    "../src/lib/curriculum/windows/problems-d",
    "../src/lib/curriculum/windows/problems-e",
  ];
  const all: Problem[] = [];
  for (const f of files) {
    try {
      const mod = await import(f);
      const arr: Problem[] = Object.values(mod).find((v) => Array.isArray(v)) as Problem[];
      if (arr) {
        all.push(...arr);
        console.log(`loaded ${f.split("/").pop()} -> ${arr.length} problems`);
      }
    } catch {
      console.log(`(skip ${f.split("/").pop()} — not authored yet)`);
    }
  }
  return all;
}

async function main() {
  const problems = await load();
  console.log(`total problems: ${problems.length}`);
  await resetDatabase();

  const out: Record<string, { columns: string[]; rows: Array<Array<string | number | null>> }> = {};
  let failures = 0;
  const seenIds = new Map<string, string>();
  const seenSql = new Map<string, string>();
  const seenResults = new Map<string, string>();
  const warnings: string[] = [];

  for (const p of problems) {
    if (seenIds.has(p.id)) {
      failures++;
      console.error(`FAIL ${p.id}: duplicate id (also in ${seenIds.get(p.id)})`);
      continue;
    }
    seenIds.set(p.id, "this run");

    const key = normSql(p.solution);
    if (seenSql.has(key)) {
      failures++;
      console.error(`FAIL ${p.id}: duplicate solution of ${seenSql.get(key)}`);
      continue;
    }
    seenSql.set(key, p.id);

    try {
      const raw = (await db.$queryRawUnsafe(p.solution)) as Array<Record<string, unknown>>;
      const columns = raw.length ? Object.keys(raw[0]) : [];
      const rows = raw.map((r) => columns.map((c) => normalizeCell(r[c])));
      out[p.id] = { columns, rows };

      const h = resultHash(columns, rows);
      const twin = seenResults.get(h);
      if (twin) {
        failures++;
        console.error(`FAIL ${p.id}: identical result set to ${twin} — problems must differ`);
      } else {
        seenResults.set(h, p.id);
      }

      if (rows.length === 0) {
        warnings.push(`WARN ${p.id}: solution returns 0 rows`);
      }
      console.log(`OK   ${p.id}  ${rows.length} rows x ${columns.length} cols`);
    } catch (err) {
      failures++;
      console.error(`FAIL ${p.id}: ${err instanceof Error ? err.message : err}`);
    }
  }

  for (const w of warnings) console.log(w);

  const banner = `// AUTO-GENERATED by scripts/wf-gen-expected.ts — do not edit by hand.
// Grading targets: each window-functions problem's solution executed on the
// freshly seeded database (${problems.length} problems, ${Object.keys(out).length} targets).

export const EXPECTED_WF: Record<
  string,
  { columns: string[]; rows: Array<Array<string | number | null>> }
> = ${JSON.stringify(out, null, 2)};
`;
  if (failures === 0) {
    writeFileSync("src/lib/curriculum/windows/expected-wf.ts", banner);
    console.log(`\nwrote expected-wf.ts with ${Object.keys(out).length} results, 0 failures`);
  } else {
    console.log(`\nNOT written — ${failures} failure(s) must be fixed first`);
    process.exit(1);
  }

  await db.$disconnect();
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main();
}
