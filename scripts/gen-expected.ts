// Generates src/lib/curriculum/expected.ts — the grading targets for every
// practice problem — by running each solution against the freshly seeded
// database. Also prints "facts" used to keep diagrams and prose honest.
//
// Run: bunx tsx scripts/gen-expected.ts

import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { db } from "../src/lib/db";
import { resetDatabase } from "../src/lib/sample-db";
import { LESSONS } from "../src/lib/curriculum/lessons";
import { ALL_GAUNTLET_PROBLEMS } from "../src/lib/curriculum/gauntlet";

function normalizeCell(v: unknown): string | number | null {
  if (v === null || v === undefined) return null;
  if (typeof v === "bigint") return Number(v);
  if (typeof v === "number") return Math.round(v * 100) / 100;
  return String(v);
}

class SandboxRollback extends Error {
  constructor() { super("__sandbox_rollback__"); }
}

/** Run a write/DDL statement (plus optional verify SELECT) inside a
 *  transaction that is always rolled back — the seed stays pristine while
 *  RETURNING rows, affected counts and the verify rows are captured. */
async function sandboxRun(
  sql: string,
  verify?: string,
): Promise<{ columns: string[]; rows: unknown[][]; changes: number }> {
  let captured: { columns: string[]; rows: unknown[][]; changes: number } | null = null;
  try {
    await db.$transaction(
      async (tx) => {
        const before = (await tx.$queryRawUnsafe(`SELECT total_changes() AS c`)) as Array<
          Record<string, unknown>
        >;
        const res = (await tx.$queryRawUnsafe(sql)) as Array<Record<string, unknown>>;
        const after = (await tx.$queryRawUnsafe(`SELECT total_changes() AS c`)) as Array<
          Record<string, unknown>
        >;
        const changes = Number(after[0].c) - Number(before[0].c);
        let list = Array.isArray(res) ? res : [];
        if (verify && verify.trim().length > 0) {
          list = (await tx.$queryRawUnsafe(verify.trim())) as Array<Record<string, unknown>>;
        }
        const columns = list.length > 0 ? Object.keys(list[0]) : [];
        captured = {
          columns,
          rows: list.map((r) => columns.map((c) => normalizeCell(r[c]))),
          changes,
        };
        throw new SandboxRollback();
      },
      { maxWait: 5000, timeout: 10_000 },
    );
  } catch (err) {
    if (!(err instanceof SandboxRollback)) throw err;
  }
  if (!captured) throw new Error(`sandbox produced no result for: ${sql.slice(0, 80)}`);
  return captured;
}

async function main() {
  const counts = await resetDatabase();
  console.log("seeded:", counts);

  const out: Record<string, { columns: string[]; rows: unknown[][] }> = {};
  let failures = 0;

  for (const lesson of LESSONS) {
    for (const p of lesson.problems) {
      try {
        if (p.mutating) {
          const got = await sandboxRun(p.solution, p.verify);
          const out2: { columns: string[]; rows: unknown[][]; changes?: number } = {
            columns: got.columns,
            rows: got.rows,
          };
          if (got.rows.length === 0) out2.changes = got.changes;
          out[p.id] = out2;
          console.log(
            `OK   ${p.id}  ${got.rows.length} rows${got.rows.length === 0 ? ` (changes=${got.changes})` : ""} [sandbox]`,
          );
        } else {
          const raw = (await db.$queryRawUnsafe(p.solution)) as Array<
            Record<string, unknown>
          >;
          const columns = raw.length ? Object.keys(raw[0]) : [];
          const rows = raw.map((r) => columns.map((c) => normalizeCell(r[c])));
          out[p.id] = { columns, rows };
          console.log(`OK   ${p.id}  ${rows.length} rows`);
        }
      } catch (err) {
        failures++;
        console.error(`FAIL ${p.id}: ${err instanceof Error ? err.message : err}`);
      }
    }
  }

  // Module gauntlet problems — same pipeline, separate banks.
  for (const p of ALL_GAUNTLET_PROBLEMS) {
    try {
      if (p.mutating) {
        const got = await sandboxRun(p.solution, p.verify);
        const out2: { columns: string[]; rows: unknown[][]; changes?: number } = {
          columns: got.columns,
          rows: got.rows,
        };
        if (got.rows.length === 0) out2.changes = got.changes;
        out[p.id] = out2;
        console.log(
          `OK   ${p.id}  ${got.rows.length} rows${got.rows.length === 0 ? ` (changes=${got.changes})` : ""} [sandbox]`,
        );
      } else {
        const raw = (await db.$queryRawUnsafe(p.solution)) as Array<
          Record<string, unknown>
        >;
        const columns = raw.length ? Object.keys(raw[0]) : [];
        const rows = raw.map((r) => columns.map((c) => normalizeCell(r[c])));
        out[p.id] = { columns, rows };
        console.log(`OK   ${p.id}  ${rows.length} rows`);
      }
    } catch (err) {
      failures++;
      console.error(`FAIL ${p.id}: ${err instanceof Error ? err.message : err}`);
    }
  }

  const banner = `// AUTO-GENERATED by scripts/gen-expected.ts — do not edit by hand.
// Grading targets: each problem's solution executed on the seed database.
// Write/DDL problems were executed sandboxed (transaction + rollback).

export const EXPECTED: Record<string, { columns: string[]; rows: Array<Array<string | number | null>>; changes?: number }> = ${JSON.stringify(out, null, 2)};
`;
  writeFileSync("src/lib/curriculum/expected.ts", banner);
  console.log(`\nwrote expected.ts with ${Object.keys(out).length} results, ${failures} failures`);

  /* ---- facts for diagrams / prose ---- */
  const q = async (sql: string) =>
    (await db.$queryRawUnsafe(sql)) as Array<Record<string, unknown>>;

  const orders = await q(`SELECT COUNT(*) AS n FROM orders`);
  const items = await q(`SELECT COUNT(*) AS n FROM order_items`);
  const bigOrders = await q(`SELECT COUNT(*) AS n FROM orders WHERE total > 200`);
  const audio = await q(`SELECT COUNT(*) AS n FROM products WHERE category = 'Audio'`);
  const marchDelivered = await q(
    `SELECT COUNT(*) AS n FROM orders WHERE status = 'delivered' AND created_at BETWEEN '2024-03-01' AND '2024-03-31'`,
  );
  const nullShip = await q(`SELECT COUNT(*) AS n FROM orders WHERE shipped_at IS NULL`);
  const top3 = await q(`SELECT id, total FROM orders ORDER BY total DESC, id ASC LIMIT 3`);
  const top5price = await q(`SELECT name, price FROM products ORDER BY price DESC LIMIT 5`);
  const statuses = await q(`SELECT status, COUNT(*) AS n FROM orders GROUP BY status ORDER BY status`);
  const topSpend = await q(
    `SELECT customer_id, ROUND(SUM(total),2) AS spend FROM orders GROUP BY customer_id ORDER BY spend DESC LIMIT 5`,
  );
  const having = await q(`SELECT status, COUNT(*) AS n FROM orders GROUP BY status HAVING COUNT(*) > 10`);
  const agg = await q(
    `SELECT COUNT(*) AS order_count, ROUND(SUM(total),2) AS revenue, ROUND(AVG(total),2) AS avg_order, ROUND(MIN(total),2) AS min_total, ROUND(MAX(total),2) AS max_total FROM orders`,
  );
  const priceRange = await q(`SELECT ROUND(MIN(price),2) AS min_price, ROUND(MAX(price),2) AS max_price FROM products`);
  const distinctCities = await q(`SELECT COUNT(*) AS n FROM (SELECT DISTINCT city, region FROM customers)`);
  const audioLike = await q(`SELECT name FROM products WHERE name LIKE '%Keyboard%'`);
  const march = await q(
    `SELECT id, customer_id, total FROM orders WHERE status='delivered' AND created_at BETWEEN '2024-03-01' AND '2024-03-31' ORDER BY id`,
  );
  const distinctCust = await q(`SELECT COUNT(*) AS n FROM (SELECT DISTINCT customer_id FROM orders)`);

  /* ---- Module 2 join facts ---- */
  const noDelivered = await q(
    `SELECT c.name FROM customers c LEFT JOIN orders o ON o.customer_id = c.id AND o.status = 'delivered' WHERE o.id IS NULL`,
  );
  const noShipped = await q(
    `SELECT c.name FROM customers c LEFT JOIN orders o ON o.customer_id = c.id AND o.status = 'shipped' WHERE o.id IS NULL`,
  );
  const regionPairs = await q(
    `SELECT COUNT(*) AS n FROM customers c1 JOIN customers c2 ON c1.region = c2.region AND c1.id < c2.id`,
  );
  const catPairs = await q(
    `SELECT COUNT(*) AS n FROM products p1 JOIN products p2 ON p1.category = p2.category AND p1.id < p2.id`,
  );
  const trueRevenue = await q(`SELECT ROUND(SUM(total), 2) AS v FROM orders`);
  const fanoutRevenue = await q(
    `SELECT ROUND(SUM(o.total), 2) AS v FROM orders o JOIN order_items oi ON oi.order_id = o.id`,
  );
  const categoryRevenue = await q(
    `SELECT p.category, ROUND(SUM(oi.quantity * oi.unit_price), 2) AS revenue FROM order_items oi JOIN products p ON p.id = oi.product_id GROUP BY p.category ORDER BY revenue DESC`,
  );

  console.log("\n--- FACTS ---");
  console.log(JSON.stringify({
    orders: orders[0].n,
    items: items[0].n,
    bigOrders: bigOrders[0].n,
    audio,
    audioNames: audioLike,
    marchDelivered: marchDelivered[0].n,
    march,
    nullShip: nullShip[0].n,
    top3,
    top5price,
    statuses,
    topSpend,
    having,
    agg: agg[0],
    priceRange: priceRange[0],
    distinctCities: distinctCities[0].n,
    distinctCust: distinctCust[0].n,
    /* module 2 */
    noDelivered,
    noShipped,
    regionPairs: regionPairs[0].n,
    catPairs: catPairs[0].n,
    trueRevenue: trueRevenue[0].v,
    fanoutRevenue: fanoutRevenue[0].v,
    categoryRevenue,
  }, (k, v) => (typeof v === "bigint" ? Number(v) : v), 2));

  await db.$disconnect();
  if (failures > 0) process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main();
}
