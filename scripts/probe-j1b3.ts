import { Database } from "bun:sqlite";
import { copyFileSync, rmSync } from "node:fs";
const COPY = "scripts/.probe-j1b3.db";
copyFileSync("db/custom.db", COPY);
const db = new Database(COPY, { readonly: true });
const q = (sql: string) => db.query(sql).all();
console.log("count>=0.5:", JSON.stringify(q(`SELECT COUNT(*) n FROM refunds r JOIN orders o ON o.id = r.order_id WHERE r.amount >= o.total * 0.5`)));
console.log("count>=0.5+cust:", JSON.stringify(q(`SELECT COUNT(*) n FROM refunds r JOIN orders o ON o.id = r.order_id JOIN customers c ON c.id = o.customer_id WHERE r.amount >= o.total * 0.5`)));
for (const r of q(`SELECT r.id, r.amount, o.total FROM refunds r JOIN orders o ON o.id = r.order_id WHERE r.amount >= o.total * 0.5 ORDER BY r.amount DESC`)) console.log(JSON.stringify(r));
console.log("md5-ish sanity:", JSON.stringify(q(`SELECT COUNT(*) refunds, ROUND(SUM(amount),2) amt FROM refunds`)));
db.close(); rmSync(COPY, { force: true });
