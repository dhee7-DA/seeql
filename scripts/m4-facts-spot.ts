import { Database } from "bun:sqlite";
import { copyFileSync, rmSync, existsSync } from "node:fs";
const SRC = "db/custom.db", COPY = ".m4spot.db";
if (existsSync(COPY)) rmSync(COPY);
copyFileSync(SRC, COPY);
const db = new Database(COPY, { readonly: true });
const g = (s: string) => JSON.stringify(db.query(s).all());
const one = (s: string) => JSON.stringify(db.query(s).get());
console.log("EXISTS shipped:", one(`SELECT COUNT(*) AS n FROM customers c WHERE EXISTS (SELECT 1 FROM orders o WHERE o.customer_id = c.id AND o.status = 'shipped')`));
console.log("APAC delivered:", one(`SELECT COUNT(*) AS n FROM customers c WHERE c.region = 'APAC' AND EXISTS (SELECT 1 FROM orders o WHERE o.customer_id = c.id AND o.status = 'delivered')`));
console.log("LATAM cancelled:", g(`SELECT c.name FROM customers c WHERE c.region = 'LATAM' AND EXISTS (SELECT 1 FROM orders o WHERE o.customer_id = c.id AND o.status = 'cancelled')`));
console.log("max total:", one(`SELECT MAX(total) AS m FROM orders`));
console.log("ties at max:", one(`SELECT COUNT(*) AS n FROM orders WHERE total = (SELECT MAX(total) FROM orders)`));
console.log("above own avg:", one(`SELECT COUNT(*) AS n FROM orders o WHERE o.total > (SELECT AVG(o2.total) FROM orders o2 WHERE o2.customer_id = o.customer_id)`));
console.log("cte shadow orders:", one(`WITH orders AS (SELECT 1 AS x) SELECT COUNT(*) AS c FROM orders`));
console.log("histogram freq n=4:", g(`SELECT n, COUNT(*) AS freq FROM (SELECT customer_id, COUNT(*) AS n FROM orders GROUP BY customer_id) GROUP BY n ORDER BY n`));
console.log("avg n>=13:", one(`SELECT ROUND(AVG(n),1) AS a FROM (SELECT n FROM (SELECT customer_id, COUNT(*) AS n FROM orders GROUP BY customer_id) WHERE n >= 13)`));
console.log("0-cancelled customers:", one(`SELECT COUNT(*) AS n FROM customers c WHERE NOT EXISTS (SELECT 1 FROM orders o WHERE o.customer_id = c.id AND o.status = 'cancelled')`));
console.log("invoices census:", one(`SELECT COUNT(*) AS n, COUNT(customer_id) AS nn FROM invoices`), one(`SELECT COUNT(DISTINCT customer_id) AS d FROM invoices`));
db.close();
