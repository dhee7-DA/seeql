import { Database } from "bun:sqlite";
import { copyFileSync, rmSync, existsSync } from "node:fs";
const SRC = "db/custom.db", COPY = ".m4in.db";
if (existsSync(COPY)) rmSync(COPY);
copyFileSync(SRC, COPY);
const db = new Database(COPY, { readonly: true });
const g = (s: string) => db.query(s).get();
console.log("EU-orders:", g(`SELECT COUNT(*) AS c FROM orders WHERE customer_id IN (SELECT id FROM customers WHERE region = 'EU')`).c);
console.log("region<=2:", g(`SELECT COUNT(*) AS c FROM customers WHERE region IN (SELECT region FROM customers WHERE id <= 2)`).c);
console.log("not-in-invoice-status:", g(`SELECT COUNT(*) AS c FROM orders WHERE status NOT IN (SELECT status FROM invoices)`).c);
console.log("cancel-cust:", g(`SELECT COUNT(*) AS c FROM customers WHERE id IN (SELECT customer_id FROM orders WHERE status = 'cancelled')`).c);
console.log("pending-shipped-notin:", g(`SELECT COUNT(*) AS c FROM orders WHERE status NOT IN ('pending','cancelled')`).c);
console.log("in-2-arg-list:", g(`SELECT COUNT(*) AS c FROM orders WHERE status IN ('pending', 'pending', 'shipped')`).c);
db.close();
