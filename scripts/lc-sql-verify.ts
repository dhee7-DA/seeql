/**
 * LeetCode SQL 50 — solution verifier + expected-result snapshot generator.
 *
 * For every LcSqlDive:
 *   1. builds the problem's schema in an in-memory SQLite (bun:sqlite),
 *   2. runs the solution (single statement, SQLite dialect),
 *   3. snapshots the result into src/lib/leetcode/content/sql-expected.ts,
 *   4. prints a digest for human review against the documented examples.
 *
 * Also enforces content invariants: unique slugs, one-statement solutions,
 * writeVerify presence iff the solution is a write, registry cross-links.
 *
 * Run: bun scripts/lc-sql-verify.ts
 */

import { Database } from "bun:sqlite";
import { LC_SQL_CONTENT, LC_CONTENT } from "../src/lib/leetcode/content/content";
import { LC_ALL } from "../src/lib/leetcode/registry";
import { splitStatements, countStatements } from "../src/lib/sql-statements";
import type { CellValue } from "../src/lib/sql-types";
import type { LcSqlExpected } from "../src/lib/leetcode/types";

/** Round floats to 4dp so snapshot vs live-run comparisons are stable. */
function norm(v: unknown): CellValue {
  const c = v as CellValue;
  if (typeof c === "number" && !Number.isInteger(c)) return Math.round(c * 10000) / 10000;
  return c;
}

const READ_START = /^(select|with)\b/i;

const fails: string[] = [];
const seenSlugs = new Set<string>();
const registryBySlug = new Map(LC_ALL.map((p) => [p.slug, p]));
const pyDiveSlugs = new Set(LC_CONTENT.map((d) => d.slug));

const expected: LcSqlExpected[] = [];

for (const dive of LC_SQL_CONTENT) {
  const tag = `[${dive.slug}]`;

  // -- invariants ----------------------------------------------------------
  if (seenSlugs.has(dive.slug)) fails.push(`${tag} duplicate slug across SQL dives`);
  seenSlugs.add(dive.slug);
  if (pyDiveSlugs.has(dive.slug)) fails.push(`${tag} slug collides with a Python deep-dive`);

  const reg = registryBySlug.get(dive.slug);
  if (!reg) fails.push(`${tag} not present in the registry`);
  else if (!reg.sql) fails.push(`${tag} registry row is not flagged as SQL`);
  else if (reg.difficulty && (reg.difficulty === "Easy" && dive.xp !== 10 || reg.difficulty === "Medium" && dive.xp !== 20 || reg.difficulty === "Hard" && dive.xp !== 35))
    fails.push(`${tag} xp ${dive.xp} does not match difficulty ${reg.difficulty}`);

  const stmts = countStatements(dive.code);
  if (stmts !== 1) fails.push(`${tag} solution must be exactly one statement (got ${stmts})`);
  const isWriteStart = /^(delete|update|insert)\b/i.test(dive.code.trim());
  if (isWriteStart && !dive.writeVerify) fails.push(`${tag} write solution missing writeVerify`);
  if (!isWriteStart && dive.writeVerify) fails.push(`${tag} read solution must not carry writeVerify`);
  if (dive.order === "exact" && !/\border\s+by\b/i.test(dive.code))
    fails.push(`${tag} order:"exact" but solution has no ORDER BY`);

  // -- execute -------------------------------------------------------------
  const db = new Database(":memory:");
  try {
    for (const s of splitStatements(dive.schema.ddl)) db.run(s);
    for (const s of splitStatements(dive.schema.seed)) db.run(s);

    const cleanCode = dive.code.replace(/;+\s*$/, "");
    let columns: string[];
    let rows: Record<string, unknown>[];
    if (isWriteStart) {
      db.run(cleanCode);
      const v = db.prepare(dive.writeVerify!.replace(/;+\s*$/, ""));
      rows = v.all() as Record<string, unknown>[];
      columns = v.columnNames;
    } else {
      const st = db.prepare(cleanCode);
      rows = st.all() as Record<string, unknown>[];
      columns = st.columnNames;
    }

    expected.push({
      slug: dive.slug,
      columns,
      rows: rows.map((r) => columns.map((c) => norm(r[c]))),
      order: dive.order,
    });

    const preview = rows.slice(0, 4).map((r) => columns.map((c) => String(r[c])).join(" | "));
    console.log(
      `OK ${dive.slug.padEnd(48)} ${String(rows.length).padStart(3)} rows · ${columns.join(", ")}`,
    );
    for (const p of preview) console.log(`     ${p}`);
    if (rows.length > 4) console.log(`     … +${rows.length - 4} more`);
  } catch (err) {
    fails.push(`${tag} FAILED: ${err instanceof Error ? err.message : String(err)}`);
  } finally {
    db.close();
  }
}

// -- cross-file coverage -----------------------------------------------------
const sqlSlugsInRegistry = new Set(LC_ALL.filter((p) => p.sql).map((p) => p.slug));
const missing = [...sqlSlugsInRegistry].filter((s) => !seenSlugs.has(s));
console.log(`\ncoverage: ${seenSlugs.size}/${sqlSlugsInRegistry.size} SQL 50 dives authored`);
if (missing.length) console.log(`missing: ${missing.join(", ")}`);

if (fails.length) {
  console.error(`\n${fails.length} FAILURE(S):`);
  for (const f of fails) console.error(`  ✗ ${f}`);
  process.exit(1);
}

// -- write the snapshot ------------------------------------------------------
const header = `// GENERATED by scripts/lc-sql-verify.ts — do not edit by hand.
// Expected result sets for the SQL 50 deep-dives: each row is the verified
// output of the dive's solution against its own seed data. Floats are
// pre-rounded to 4dp to match the client-side comparison.
import type { LcSqlExpected } from "../types";

export const SQL_EXPECTED: LcSqlExpected[] = ${JSON.stringify(expected, null, 2)};

const bySlug = new Map(SQL_EXPECTED.map((e) => [e.slug, e]));

/** Expected answer snapshot for a SQL problem, if authored. */
export const lcSqlExpected = (slug: string) => bySlug.get(slug);
`;

const out = new URL("../src/lib/leetcode/content/sql-expected.ts", import.meta.url).pathname;
await Bun.write(out, header);
console.log(`\nsnapshot written: ${out} (${expected.length} problems) — all checks passed`);
