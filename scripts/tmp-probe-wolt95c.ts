import { Database } from "bun:sqlite";
import { copyFileSync, rmSync } from "node:fs";
const COPY = "scripts/.probe-wolt95c.db";
copyFileSync("db/custom.db", COPY);
const db = new Database(COPY, { readonly: true });
const n = db.query("SELECT q, COUNT(*) AS n FROM (SELECT NTILE(4) OVER (ORDER BY total) AS q FROM orders) GROUP BY q ORDER BY q").all();
console.log("ntile4 over 103:", JSON.stringify(n));
const r2 = db.query("SELECT name FROM (SELECT c.name, RANK() OVER (ORDER BY SUM(o.total)) AS r FROM orders o JOIN customers c ON c.id=o.customer_id GROUP BY c.name) WHERE r = 1").all();
console.log("rank1 ASC:", JSON.stringify(r2));
db.close();
rmSync(COPY, { force: true });
