/// <reference types="bun-types" />
// Task 106 — build-time codegen for the universal strip.
// Derives universe totals from the kit registry and writes a tiny standalone
// constants file, so UI surfaces (landing, playground, learn) never need to
// import the full kit registry (~23 MB of source) just to show six numbers.
//
// Run: bun run gen:counts   (also wired as the prebuild hook)
// Output: src/lib/generated/universe-counts.ts (committed; fully deterministic)
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { COMPANY_KITS, COMPANY_DOMAINS } from "../src/lib/companies/registry";

const kits = Object.values(COMPANY_KITS);
const counts = {
  companies: kits.length,
  domains: COMPANY_DOMAINS.length,
  problems: kits.reduce((a, k) => a + k.problems.length, 0),
  theory: kits.reduce((a, k) => a + k.theory.length, 0),
  mcqs: kits.reduce((a, k) => a + k.mcqs.length, 0),
  cases: kits.reduce((a, k) => a + k.cases.length, 0),
} as const;

const banner = `// AUTO-GENERATED by scripts/gen-universe-counts.ts — do not edit by hand.
// Source of truth: src/lib/companies/registry.ts (derived over all ${counts.companies} kit modules).
// Regenerate with: bun run gen:counts
// Exists so the universal strip can show universe totals without importing
// the full kit registry into the client bundle.
`;

const body = `export const UNIVERSE_COUNTS = ${JSON.stringify(counts, null, 2)} as const;

export type UniverseCountKey = keyof typeof UNIVERSE_COUNTS;
`;

const outDir = join(import.meta.dir, "..", "src", "lib", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "universe-counts.ts"), banner + body);

console.log(
  `universe-counts.ts written — ${counts.companies} companies · ${counts.domains} domains · ` +
    `${counts.problems} problems · ${counts.theory} theory · ${counts.mcqs} mcqs · ${counts.cases} cases`,
);
