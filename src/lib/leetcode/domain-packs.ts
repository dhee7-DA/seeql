// Domain Mastery — pack registry, types and ledger wiring.
//
// A domain pack is a complete practice world for one business domain: ONE
// shared schema+seed, 6-8 anchor companies (real registry employers where
// they fit + fictional carriers for the heavier cases), and three question
// banks in equal measure — 60 query problems, 60 MCQs, 60 case studies,
// each bank balanced 20 Easy / 20 Medium / 20 Hard.
//
// Grading is the honest ledger, same as everywhere else in the band:
//   dm:<pack>:q:<id>          query problem solved (LC_XP by difficulty)
//   dm:<pack>:m:<id>          MCQ answered correctly FIRST TRY (DmMcqXp)
//   dm:<pack>:c:<id>:<step>   case-study step solved (DmCaseXp by difficulty)
// The engine-verified expected outputs live in content/dm-expected.ts —
// generated by scripts/r9-dm-verify.ts, never hand-edited.

import { LC_XP } from "./types";
import { DM_RETAIL_SCHEMA } from "./content/dm-retail-schema";
import { DM_RETAIL_SEED } from "./content/dm-retail-seed";
import { DM_RETAIL_QUERIES } from "./content/dm-retail-queries";
import { DM_RETAIL_MCQS } from "./content/dm-retail-mcqs";
import { DM_RETAIL_CASES } from "./content/dm-retail-cases";

export type DmDifficulty = "Easy" | "Medium" | "Hard";

export interface DmCompany {
  name: string;
  /** real = registry-sourced employer flavor; fictional = original carrier */
  real: boolean;
  blurb: string;
}

export interface DmQuery {
  id: string;
  difficulty: DmDifficulty;
  company: string;
  title: string;
  statement: string;
  code: string;
  order: "exact" | "any";
}

export interface DmMcq {
  id: string;
  difficulty: DmDifficulty;
  company: string;
  /** output = pick the true result of a real query (mutant-verified);
   *  concept = hand-authored knowledge check grounded in probed facts */
  kind: "output" | "concept";
  prompt: string;
  /** kind=output: the true query + 3 mutants with provably different output */
  truthQuery?: string;
  mutantQueries?: string[];
  options: string[];
  answer: number;
  explain: string;
}

export interface DmCaseStep {
  prompt: string;
  code: string;
  order: "exact" | "any";
}

export interface DmCase {
  id: string;
  difficulty: DmDifficulty;
  company: string;
  title: string;
  scenario: string;
  steps: DmCaseStep[];
}

export interface DmPack {
  id: string;
  title: string;
  tagline: string;
  companies: DmCompany[];
  schema: { ddl: string; seed: string; tables: { name: string; note: string }[] };
  primer: { hook: string; concept: string[]; glossary: Array<{ term: string; def: string }> };
  queries: DmQuery[];
  mcqs: DmMcq[];
  cases: DmCase[];
}

export const DM_MCQ_XP: Record<DmDifficulty, number> = { Easy: 4, Medium: 6, Hard: 9 };
export const DM_CASE_XP: Record<DmDifficulty, number> = { Easy: 8, Medium: 12, Hard: 18 };
export const dmQueryXp = (d: DmDifficulty) => LC_XP[d];

export const dmQueryKey = (pack: string, id: string) => `dm:${pack}:q:${id}`;
export const dmMcqKey = (pack: string, id: string) => `dm:${pack}:m:${id}`;
export const dmCaseKey = (pack: string, id: string, step: number) => `dm:${pack}:c:${id}:${step}`;

