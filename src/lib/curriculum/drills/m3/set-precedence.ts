// subquery wrap groups instead: statuses ∖ (regions ∪ cities) = 4; a trailing
// UNION dedups everything before it: 206 UNION ALL rows + UNION regions → 8;
// mid-arm ORDER BY → "ORDER BY clause should come after UNION not before";
// mid-arm LIMIT → "LIMIT clause should come after UNION not before";
